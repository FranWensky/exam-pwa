def text(block):
    return block["text"] if "text" in block else parse_html(block["html"])[0]


def illustration(src, height, caption, alt):
    return {"kind": "figure", "src": f"./figures/{src}", "width": 1200,
            "height": height, "caption": caption, "alt": alt}


def insert(blocks, anchor, figure, after=False):
    index = next((i + int(after) for i, block in enumerate(blocks)
                  if block["kind"] != "figure" and text(block).startswith(anchor)), len(blocks))
    blocks.insert(index, figure)


def add_figures(title, blocks):
    match = re.match(r"§\s*(\d+)\.", title)
    if not match:
        return
    number = int(match[1])
    if number == 7:
        for i, (anchor, height, caption, alt) in enumerate(VECTORS, 1):
            insert(blocks, anchor, illustration(f"vectors-{i}.png", height, f"Рис. {i}. {caption}", alt))
        blocks[:] = [block for block in blocks if block["kind"] == "figure"
                     or not re.match(r"(?:Рисунки к § 7 приведены в HTML-версии|Рис\. [1-5]\. )", text(block))]
    elif number in ALGEBRA:
        anchor, caption, alt = ALGEBRA[number]
        height = 649 if number == 5 else 510
        insert(blocks, anchor, illustration(f"algebra-{number}.svg", height, caption, alt), after=number == 8)
