def clean_line(line):
    if line.strip() in OMIT or SLIDES.match(line):
        return None
    if line in REWRITE:
        return REWRITE[line]
    line = PHOTO_LABEL.sub("", line)
    for old, new in PHRASES:
        line = line.replace(old, new)
    if line.startswith(("<i>", "<b>")):
        line = re.sub(r" из лекци[ий](?=</[ib]>| при | по )", "", line)
    if line.endswith("?"):
        line = re.sub(r" (?:привед[её]н\w*|перечислен\w*|дан\w*|назван\w*|рассматрива\w*|показан\w*|выделен\w*) (?:в конспекте|в лекции|на слайдах)\?", "?", line)
        line = re.sub(r" (?:по записи в конспекте|в конспекте|из конспекта|по лекции|в лекции|на слайде о выводе)\?", "?", line)
        line = line.replace("Как в конспекте ", "Как ").replace("Как в лекции ", "Как ")
        line = line.replace(",?", "?")
    return line


def clean_text(value):
    return "\n".join(cleaned for line in value.split("\n")
                     if (cleaned := clean_line(line)) is not None)


def clean_blocks(blocks):
    result = []
    for block in blocks:
        if block["kind"] in {"code", "figure"}:
            result.append(block)
            continue
        key = "text" if "text" in block else "html"
        value = block[key]
        if value.startswith("<i>Повторная запись на фото 16"):
            # The preceding block already has both correct formulas.
            continue
        value = clean_text(value)
        # Match just the two matrices whose cofactor was miscopied.
        if value.startswith(("     ⎡ −2  2   4 ⎤\nA′", "     ⎡ −2   3  −7 ⎤\nÃ")):
            value = value.replace("−7  5  −6", "−7 −5  −6").replace("2   1   5", "2   1  −5")
        if "Подписано R₂ ← R₂ − R₁," in value:
            value = value.replace("Подписано R₂", "R₂").replace("0   2   1   4", "0   3   1  −2")
        if value.startswith("R₃ ← R₃ − 3R₂,  R₄ ← R₄ + R₂\n"):
            result.append({"kind": "heading", "text": "Другой пример: система ранга 2"})
            value = value.split("\n", 1)[1].replace("  ∼ ⎢", "    ⎢", 1)
        if value.strip():
            result.append({**block, key: value})
    return result
